const assert=require('node:assert/strict');
const clock=require('../dashboard/round-clock.js');
const round={status:'RUNNING',started_at:100000,paused_ms:0,duration_ms:3600000};
assert.equal(clock({...round,status:'DRAFT'},80000),'Not started');
assert.equal(clock(round,70000),'Starts in 00:30');
assert.equal(clock(round,100000),'60:00');
assert.equal(clock(round,105000),'59:55');
assert.equal(clock({...round,status:'PAUSED',paused_at:105000},120000),'59:55');
assert.equal(clock({...round,paused_ms:15000},120000),'59:55');
assert.equal(clock({...round,status:'ENDED'},120000),'00:00');
assert.equal(clock({...round,duration_ms:0},70000),'Starts in 00:30');
assert.equal(clock({...round,duration_ms:0},100000),'No time limit');
assert.equal(clock({...round,duration_ms:0},999999999),'No time limit');
assert.equal(clock({...round,duration_ms:0,status:'PAUSED',paused_at:105000},120000),'Paused · no limit');
assert.equal(clock({...round,duration_ms:0,status:'ENDED'},120000),'00:00');
console.log('Shared web countdown and deadline checks passed.');
assert.equal(clock.finishTime(Date.UTC(2026,9,30,8,5,9,123)),'2026-10-30 13:35:09.123 IST');
assert.equal(clock.finishTime(null),'—');assert.equal(clock.elapsedTime(3723456),'01:02:03.456');assert.equal(clock.elapsedTime(0),'00:00:00.000');
console.log('Winner timestamps retain seconds, milliseconds and explicit IST; elapsed time retains milliseconds.');
